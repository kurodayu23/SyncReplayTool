//
// 改版本号时**只改这里**，其余三处跟着走。
//
// 版本号规则：主版本.次版本.修订号
//   · 主版本：交付形态/不兼容变更（大改、换了 Qt 大版本、配置格式不兼容）
//   · 次版本：功能增加或缺陷修复（每个正式交付包一次）
//   · 修订号：同一次交付内的补丁轮次（一般不动）
